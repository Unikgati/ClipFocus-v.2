import Foundation
import CoreGraphics

/// Easing curve style for camera pan and zoom transitions
public enum ZoomEasingCurve: String, Codable, Sendable {
    case easeInOutCubic = "ease_in_out_cubic"
    case springSmooth = "spring_smooth"
    case linear = "linear"
}

/// Zoom Effect style matching FocuSee (2D Zoom vs 3D Motion)
public enum ZoomEffectType: String, CaseIterable, Codable, Sendable {
    case zoom2D = "2D Zoom"
    case motion3D = "3D Motion"
}

/// Advanced 3D Tilt Mode — flexible, real 3D rotation system
///
/// - `flat`: No 3D tilt — perfectly flat card
/// - `auto`: Dynamic 3D tilt that follows the focus point direction (like FocuSee).
///   Zooming to the top-right tilts the card toward top-right naturally.
/// - `custom`: Full manual control via individual pitch/yaw/roll values stored per keyframe
public enum TiltPreset: String, CaseIterable, Codable, Sendable {
    case flat = "Flat"
    case auto = "Auto"
    case custom = "Custom"
    
    /// Calculate angles for a given focus point and custom overrides.
    /// - For `flat`: always zero
    /// - For `auto`: dynamically computed from where the camera is pointing (focus point)
    /// - For `custom`: uses the provided custom pitch/yaw/roll values
    public func angles(
        focusPoint: CGPoint = CGPoint(x: 0.5, y: 0.5),
        customPitch: Double = 0.0,
        customYaw: Double = 0.0,
        customRoll: Double = 0.0
    ) -> (pitch: Double, yaw: Double, roll: Double) {
        switch self {
        case .flat:
            return (pitch: 0.0, yaw: 0.0, roll: 0.0)
        case .auto:
            // Dynamic 3D: tilt follows focus point direction — the core of FocuSee's 3D magic.
            // When zoomed into top-right, the card tilts as if you're looking at it from that angle.
            let pitch = (focusPoint.y - 0.5) * -16.0
            let yaw = (focusPoint.x - 0.5) * 18.0
            let roll = ((focusPoint.x - 0.5) * (focusPoint.y - 0.5)) * -8.0
            return (pitch: pitch, yaw: yaw, roll: roll)
        case .custom:
            return (pitch: customPitch, yaw: customYaw, roll: customRoll)
        }
    }
}

/// A keyframe representing zoom depth and focus position on the screen canvas
public struct ZoomKeyframe: Codable, Identifiable, Sendable {
    public let id: UUID
    public var startTime: TimeInterval
    public var duration: TimeInterval
    
    /// Target center of focus in normalized coordinates (0.0, 0.0) is top-left, (1.0, 1.0) is bottom-right
    public var focusPoint: CGPoint
    
    /// Zoom scale factor: 1.0 = full screen (1X - no zoom), 1.5 = 150%, 2.0 = 200%
    public var scale: CGFloat
    
    /// Transition animation curve
    public var easing: ZoomEasingCurve
    
    /// 2D Zoom vs 3D Motion
    public var effectType: ZoomEffectType
    
    /// 3D Tilt Mode (Flat / Auto / Custom)
    public var tiltPreset: TiltPreset
    
    /// Custom 3D rotation angles (degrees) — used when tiltPreset == .custom
    public var customPitch: Double
    public var customYaw: Double
    public var customRoll: Double
    
    /// 2D Position Offset (X and Y Pan)
    public var positionOffsetX: CGFloat
    public var positionOffsetY: CGFloat
    
    /// Whether this keyframe was auto-generated by the AI clustering engine or manually adjusted by the user
    public var isAutoGenerated: Bool
    
    /// Contextual reason for the zoom (e.g. "click_cluster", "text_input", "manual")
    public var reason: String?
    
    /// Resolved 3D angles for this keyframe, accounting for tilt mode
    public var resolvedAngles: (pitch: Double, yaw: Double, roll: Double) {
        return tiltPreset.angles(
            focusPoint: focusPoint,
            customPitch: customPitch,
            customYaw: customYaw,
            customRoll: customRoll
        )
    }

    public init(
        id: UUID = UUID(),
        startTime: TimeInterval,
        duration: TimeInterval,
        focusPoint: CGPoint,
        scale: CGFloat = 1.0,
        easing: ZoomEasingCurve = .springSmooth,
        effectType: ZoomEffectType = .motion3D,
        tiltPreset: TiltPreset = .auto,
        customPitch: Double = 0.0,
        customYaw: Double = 0.0,
        customRoll: Double = 0.0,
        positionOffsetX: CGFloat = 0.0,
        positionOffsetY: CGFloat = 0.0,
        isAutoGenerated: Bool = true,
        reason: String? = nil
    ) {
        self.id = id
        self.startTime = startTime
        self.duration = duration
        self.focusPoint = focusPoint
        self.scale = scale
        self.easing = easing
        self.effectType = effectType
        self.tiltPreset = tiltPreset
        self.customPitch = customPitch
        self.customYaw = customYaw
        self.customRoll = customRoll
        self.positionOffsetX = positionOffsetX
        self.positionOffsetY = positionOffsetY
        self.isAutoGenerated = isAutoGenerated
        self.reason = reason
    }
    
    enum CodingKeys: String, CodingKey {
        case id, startTime, duration, focusPoint, scale, easing
        case effectType, tiltPreset, customPitch, customYaw, customRoll
        case positionOffsetX, positionOffsetY
        case isAutoGenerated, reason
    }
    
    public init(from decoder: Decoder) throws {
        let container = try decoder.container(keyedBy: CodingKeys.self)
        id = try container.decodeIfPresent(UUID.self, forKey: .id) ?? UUID()
        startTime = try container.decode(TimeInterval.self, forKey: .startTime)
        duration = try container.decode(TimeInterval.self, forKey: .duration)
        focusPoint = try container.decode(CGPoint.self, forKey: .focusPoint)
        scale = try container.decode(CGFloat.self, forKey: .scale)
        easing = try container.decodeIfPresent(ZoomEasingCurve.self, forKey: .easing) ?? .springSmooth
        effectType = try container.decodeIfPresent(ZoomEffectType.self, forKey: .effectType) ?? .motion3D
        // Migration: legacy presets map to .auto (the closest natural 3D behavior)
        let rawPreset = try container.decodeIfPresent(TiltPreset.self, forKey: .tiltPreset)
        tiltPreset = rawPreset ?? .auto
        customPitch = try container.decodeIfPresent(Double.self, forKey: .customPitch) ?? 0.0
        customYaw = try container.decodeIfPresent(Double.self, forKey: .customYaw) ?? 0.0
        customRoll = try container.decodeIfPresent(Double.self, forKey: .customRoll) ?? 0.0
        positionOffsetX = try container.decodeIfPresent(CGFloat.self, forKey: .positionOffsetX) ?? 0.0
        positionOffsetY = try container.decodeIfPresent(CGFloat.self, forKey: .positionOffsetY) ?? 0.0
        isAutoGenerated = try container.decodeIfPresent(Bool.self, forKey: .isAutoGenerated) ?? false
        reason = try container.decodeIfPresent(String.self, forKey: .reason)
    }
}
